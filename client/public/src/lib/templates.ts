/**
 * DBCreator — Built-in Application Templates
 * 6 complete application blueprints ready to install in one click.
 * Each template defines tables, fields, relationships, forms, reports, and menus.
 */

export interface TemplateField {
  name: string;
  label: string;
  type: string;
  required?: boolean;
  isPrimary?: boolean;
  defaultValue?: string;
  lovValues?: string; // JSON array string for LOV fields
  referencedTableName?: string; // resolved to ID at install time
  description?: string;
}

export interface TemplateTable {
  name: string;
  displayName: string;
  description?: string;
  tableType?: string;
  color?: string;
  fields: TemplateField[];
}

export interface TemplateRelationship {
  masterTableName: string;
  detailTableName: string;
  foreignKeyFieldName: string;
  relationshipType?: string;
  cascadeDelete?: boolean;
}

export interface TemplateFormField {
  fieldName: string;
  label?: string;
  required?: boolean;
  hidden?: boolean;
  order?: number;
}

export interface TemplateForm {
  name: string;
  displayName: string;
  description?: string;
  tableName: string;
  formFields: TemplateFormField[];
  detailFormNames?: string[]; // resolved to IDs at install time
}

export interface TemplateReportColumn {
  fieldName: string;
  label?: string;
  sortable?: boolean;
  filterable?: boolean;
}

export interface TemplateReport {
  name: string;
  displayName: string;
  description?: string;
  tableName: string;
  columns: TemplateReportColumn[];
  defaultSortField?: string;
  defaultSortDir?: 'asc' | 'desc';
}

export interface TemplateMenuItem {
  label: string;
  icon?: string;
  type: 'form' | 'report' | 'separator' | 'group';
  targetName?: string; // form or report name
  order: number;
}

export interface TemplateMenu {
  name: string;
  displayName: string;
  description?: string;
  items: TemplateMenuItem[];
}

export interface AppTemplate {
  id: string;
  name: string;
  tagline: string;
  description: string;
  category: string;
  color: string;       // CSS gradient for card
  accentColor: string; // hex for badge
  icon: string;        // emoji
  tableCount: number;
  formCount: number;
  reportCount: number;
  tables: TemplateTable[];
  relationships: TemplateRelationship[];
  forms: TemplateForm[];
  reports: TemplateReport[];
  menus: TemplateMenu[];
  // Optional mock data rows to seed on install.
  // Keys are table names; values are arrays of row objects.
  // FK values can use '@tableName[index]' to reference previously seeded rows.
  mockData?: Record<string, Record<string, unknown>[]>;
}

